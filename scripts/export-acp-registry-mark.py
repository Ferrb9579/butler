#!/usr/bin/env python3
"""Verify the official black ACP asset and export its native Canvas geometry."""
import argparse
import hashlib
from pathlib import Path
import re
import runpy
from xml.etree import ElementTree

ROOT = Path(__file__).resolve().parent.parent
ASSET = ROOT / "assets/brands/acp-mark-black.svg"
RUST = ROOT / "src/acp_registry_mark_generated.rs"
ASSET_SHA256 = "d75028b33a5eaf8edd686c2fa70adee10ddd0c31dab614d2f2bd2fe00feb87f7"


def main():
    cli = argparse.ArgumentParser(description=__doc__)
    cli.add_argument("--check", action="store_true")
    cli.add_argument("--t3-icons-source", type=Path, metavar="ICONS_TSX")
    args = cli.parse_args()

    source = ASSET.read_bytes()
    if hashlib.sha256(source).hexdigest() != ASSET_SHA256:
        raise ValueError("expected the original official ACP pure-black SVG")
    svg = ElementTree.fromstring(source)
    (path,) = tuple(svg)
    view_box = svg.attrib["viewBox"]
    d = path.attrib["d"]
    if (
        svg.tag != "{http://www.w3.org/2000/svg}svg"
        or view_box != "0 0 576 220"
        or path.tag != "{http://www.w3.org/2000/svg}path"
        or path.attrib != {"d": d, "fill": "black"}
    ):
        raise ValueError("unexpected ACP artwork")

    if args.t3_icons_source is not None:
        ref = args.t3_icons_source.read_text(encoding="utf-8")
        block = ref.split("export const ACPRegistryIcon:", 1)[1].split("export const ", 1)[0]
        if (
            re.search(r'viewBox="([^"]+)"', block)[1] != view_box
            or re.search(r'<path d="([^"]+)"', block)[1] != d
        ):
            raise ValueError("the ACP path or viewBox differs from the reference")

    geometry = runpy.run_path(str(ROOT / "scripts/export-reference-icons.py"))["rust_geometry"]
    _, filled = geometry([("path", {"d": d, "fill": "currentColor"})])
    lines = [
        "// @generated by scripts/export-acp-registry-mark.py; don't edit manually.",
        "use super::Segment::{self, C, L, M, Z};",
        "",
        "#[rustfmt::skip]",
        "pub(super) const PATH: &[Segment] = &[",
        *(f"    {command}," for command in filled),
        "];",
        "",
    ]
    generated = "\n".join(lines).encode()
    if args.check:
        if RUST.read_bytes() != generated:
            raise ValueError("generated ACP geometry is stale")
    else:
        RUST.write_bytes(generated)
    print("Verified the official pure-black ACP mark and native path.")


if __name__ == "__main__":
    main()
